def _care_n(row):
    try:
        return max(0, int((row or {}).get("care") or 0))
    except (TypeError, ValueError):
        return 0


def _food_bounds(rows):
    found = []
    for row in rows or []:
        if str((row or {}).get("id") or "") in _FOOD_IDS:
            found.append(_care_n(row))
    if not found:
        found = [8, 12, 15]
    return min(found), max(found)


