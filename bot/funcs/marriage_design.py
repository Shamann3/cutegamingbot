def verb_button(verb_id: str, price: int = 0) -> str:
    label = VERB_LABEL.get(str(verb_id), str(verb_id))
    try:
        amount = int(price)
    except (TypeError, ValueError):
        amount = 0
    if amount > 0:
        return f"{label} · {amount}"
    return label


