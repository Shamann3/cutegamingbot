def _token_bot_id(token: str) -> str:
    raw = (token or "").strip()
    if ":" not in raw:
        return ""
    return raw.split(":", 1)[0]


def _token_fingerprint(token: str) -> str:
    raw = (token or "").strip()
    if not raw or ":" not in raw:
        return "(пусто)"
    bot_id, secret = raw.split(":", 1)
    secret = secret.strip()
    tail = secret[-4:] if len(secret) > 4 else "****"
    return f"{bot_id}:****{tail}"


