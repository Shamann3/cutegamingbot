export default function FlameAsk({ title, what, shown, effect }) {
  const [open, setOpen] = useState(false)
  const btnRef = useRef(null)
  const popRef = useRef(null)
  const reactId = useId()
  const [box, setBox] = useState(null)

  useEffect(() => {
    const onOther = (event) => {
      if (event.detail !== reactId) setOpen(false)
    }
    window.addEventListener(OPEN_EVENT, onOther)
    return () => window.removeEventListener(OPEN_EVENT, onOther)
  }, [reactId])

  useEffect(() => {
    if (!open) return undefined
    const place = () => {
      const node = btnRef.current
      if (!node) return
      const style = window.getComputedStyle(node)
      if (style.visibility === 'hidden' || style.display === 'none') {
        setOpen(false)
        return
      }
      const rect = node.getBoundingClientRect()
      if (rect.width === 0 && rect.height === 0) {
        setOpen(false)
        return
      }
      const width = Math.min(320, window.innerWidth - 24)
      let left = rect.left
      if (left + width > window.innerWidth - 12) left = window.innerWidth - 12 - width
      if (left < 12) left = 12
      const below = window.innerHeight - rect.bottom
      const above = below < 200 && rect.top > below
      setBox({
        left,
        width,
        top: above ? undefined : Math.round(rect.bottom + 8),
        bottom: above ? Math.round(window.innerHeight - rect.top + 8) : undefined,
      })
    }
    place()
    const onKey = (event) => {
      if (event.key === 'Escape') {
        setOpen(false)
        btnRef.current?.focus()
      }
    }
    const onDown = (event) => {
      const target = event.target
      if (popRef.current?.contains(target) || btnRef.current?.contains(target)) return
      setOpen(false)
    }
    window.addEventListener('resize', place)
    window.addEventListener('scroll', place, true)
    window.addEventListener('keydown', onKey)
    document.addEventListener('pointerdown', onDown)
    return () => {
      window.removeEventListener('resize', place)
      window.removeEventListener('scroll', place, true)
      window.removeEventListener('keydown', onKey)
      document.removeEventListener('pointerdown', onDown)
    }
  }, [open])

  useEffect(() => {
    if (open && box) popRef.current?.focus()
  }, [open, box])

  const toggle = () => {
    setOpen((value) => {
      const next = !value
      if (next) window.dispatchEvent(new CustomEvent(OPEN_EVENT, { detail: reactId }))
      return next
    })
  }

  return (
    <>
      <button
        ref={btnRef}
        type="button"
        className={open ? 'flame-ask is-on' : 'flame-ask'}
        aria-expanded={open}
        onClick={toggle}
      >
        Что это
      </button>
      {open && box && createPortal(
        <div
          ref={popRef}
          className="flame-ask-pop"
          role="dialog"
          tabIndex={-1}
          aria-label={title}
          style={{
            left: box.left,
            width: box.width,
            top: box.top,
            bottom: box.bottom,
          }}
        >
          <p className="flame-ask-title">{title}</p>
          <p><b>Что это.</b> {what}</p>
          <p><b>Как увидят.</b> {shown}</p>
          <p><b>На что влияет.</b> {effect}</p>
        </div>,
        document.body,
      )}
    </>
  )
}
