/** Текст, когда своего ключа на экране нет. Готовый ключ сюда не кладётся. */

const STAFF = {
  none: 'Входа в панель сотрудника у вас нет.',
  closed: 'Доступ к панели сотрудника выключен. Действующего ключа нет.',
  server: 'Отдельной копии нет: вход владельца идёт ключом сервера, и панель его не показывает.',
  unstored: 'Этот ключ выдан раньше, чем панель стала его хранить. Новый может выдать создатель: сначала отключить доступ, потом выдать ключ.',
}

const GROUP = {
  none: 'Ключа кабинета группы нет.',
  closed: 'Кабинет выключен. Старый ключ уже не действует.',
  unstored: 'Копии этого ключа нет: он выдан до того, как панель стала его хранить. Новый появится, если доступ отключат и выдадут ключ заново.',
}

export function doorKeyLine(door, state) {
  const table = door === 'staff' ? STAFF : GROUP
  return table[state] || 'Ключ не открылся.'
}
