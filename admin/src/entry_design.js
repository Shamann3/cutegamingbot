/**
 * Вход в панели — дизайн подсказок.
 *
 * Как править
 * -----------
 * Каждый экран входа — блок в SCREENS ниже.
 *   tab   — как экран называется в предпросмотре у создателя.
 *   title — заголовок над шагами.
 *   steps — шаги по порядку: title — что сделать, line — одна-две строки под шагом.
 *   more  — полный текст за кнопкой «Подробнее», внутри обратных кавычек `…`.
 * id шагов не трогайте: по ним экран понимает, какой шаг сейчас.
 *
 * Подписи полей и кнопок — в WORDS, обычными кавычками, без тегов.
 * Поменяли подпись в WORDS — поправьте её и в more: там названы те же поля и кнопки.
 *
 * Разметка в more
 * ---------------
 * Пустая строка — новый абзац.
 * # Заголовок — новый раздел.
 * 1. 2. 3. — нажатия по порядку.
 * • — пункт списка.
 *
 * Типографика
 * -----------
 * <b>жирный</b> — то, что человек видит на экране: поле, кнопка, вкладка.
 * <i>курсив</i> — навигация в телефоне и в приложении: что нажать, куда зайти.
 * <u>подчёркнутый</u> — только самое важное: шесть цифр, 30 секунд.
 * <code>код</code> — то, что пишут руками.
 * Другие теги покажутся как обычный текст.
 *
 * Где посмотреть
 * --------------
 * Создатель видит все подсказки в панели: «Стафф» → «Сотрудники» или «Администраторы» → «Ключи».
 * Люди увидят правку после пересборки панели.
 */

/** Срезает общий отступ у текста в обратных кавычках, строки внутри оставляет. */
export function t(text) {
  const lines = String(text ?? '').replace(/^\n+/, '').replace(/\s+$/, '').split('\n')
  const pads = lines.filter((line) => line.trim()).map((line) => line.match(/^ */)[0].length)
  const pad = pads.length ? Math.min(...pads) : 0
  return lines.map((line) => line.slice(pad)).join('\n')
}

